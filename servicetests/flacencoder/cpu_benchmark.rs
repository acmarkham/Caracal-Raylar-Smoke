//! Intrinsic codec cycle benchmark. No capture, SD writes, GPS or radio.
#![no_std]
#![no_main]
extern crate alloc;

#[path = "../storage/common.rs"]
#[allow(dead_code)]
mod common;

use core::hint::black_box;
use cortex_m::peripheral::DWT;
use defmt::{info, unwrap};
use embassy_executor::Spawner;
use embassy_time::{Instant, Timer};
use embedded_alloc::LlffHeap;
use raylar_drivers::stm32_core::{CoreConfig, CoreSupply, stm32::Stm32CoreDriver};
use raylar_flac_encoder_service::{
    BenchmarkOptions, Config, Encoder, RiceMethod, Search, Subframe,
};
use static_cell::ConstStaticCell;
use {defmt_rtt as _, panic_probe as _};

#[global_allocator]
static HEAP: LlffHeap = LlffHeap::empty();
static PCM: ConstStaticCell<[i32; 4096]> = ConstStaticCell::new([0; 4096]);
static FRAME: ConstStaticCell<[u8; 16416]> = ConstStaticCell::new([0; 16416]);
// Generated by prepare_cpu_corpus.py; only the opt-in benchmark uses this file.
static CORPUS: &[u8] = include_bytes!("../../target/flac-cpu/corpus.s32le");
const REPEATS: usize = 2;

#[derive(Default)]
struct Totals {
    select: u64,
    emit: u64,
    maximum: u32,
    bytes: usize,
    samples: usize,
    frames: usize,
    orders: [usize; 5],
    verbatim: usize,
    constant: usize,
    rice4: usize,
    rice5: usize,
}

fn input(pcm: &mut [i32], start: usize, depth: u8, data: u8, signed_width: u8) {
    let mut state = 0x12345678u32.wrapping_add(start as u32);
    for (i, sample) in pcm.iter_mut().enumerate() {
        *sample = match data {
            0 => {
                let offset = (start + i) * 4;
                i32::from_le_bytes(CORPUS[offset..offset + 4].try_into().unwrap())
                    >> signed_width.saturating_sub(depth)
            }
            1 => 0,
            _ => {
                state ^= state << 13;
                state ^= state >> 17;
                state ^= state << 5;
                (state as i32) >> (32 - depth)
            }
        };
    }
}

fn wav(samples: &[i32], depth: u8, output: &mut [u8]) -> usize {
    let width = depth as usize / 8;
    if depth == 8 {
        for (sample, byte) in samples.iter().zip(output.iter_mut()) {
            *byte = (*sample + 128) as u8;
        }
    } else {
        for (sample, bytes) in samples.iter().zip(output.chunks_exact_mut(width)) {
            bytes.copy_from_slice(&sample.to_le_bytes()[..width]);
        }
    }
    samples.len() * width
}

async fn run(
    pcm: &mut [i32],
    output: &mut [u8],
    width: u8,
    data: u8,
    depth: u8,
    block: usize,
    codec: u8,
    order: u8,
    method: u8,
    search: u8,
) {
    let mut totals = Totals::default();
    let mut encoder = unwrap!(Encoder::new(Config {
        bits_per_sample: depth,
        block_samples: block,
        sample_rate_hz: 16000,
        prediction: if cfg!(feature = "cpu-benchmark-fixed-order1") {
            raylar_flac_encoder_service::Prediction::Fixed(1)
        } else {
            raylar_flac_encoder_service::Prediction::Auto
        },
    }));
    let options = BenchmarkOptions {
        order: if order == 255 { None } else { Some(order) },
        rice: match method {
            1 => RiceMethod::Four,
            2 => RiceMethod::Five,
            _ => RiceMethod::Auto,
        },
        search: match search {
            1 => Search::Exhaustive,
            2 => Search::MeanNeighbors,
            3 => Search::MeanNeighborsFused,
            _ => Search::BitCounts,
        },
    };
    for _ in 0..REPEATS {
        encoder.reset();
        for start in (0..CORPUS.len() / 4).step_by(block) {
            input(&mut pcm[..block], start, depth, data, width);
            // Only timer interrupts can run. Keep them enabled so even a slow
            // exhaustive search cannot lose Embassy timer-overflow accounting.
            let began = DWT::cycle_count();
            let (select, emit, bytes, frame) = if codec == 0 {
                let bytes = wav(black_box(&pcm[..block]), depth, black_box(output));
                black_box(&output[..bytes]);
                (0, DWT::cycle_count().wrapping_sub(began), bytes, None)
            } else {
                let analysis = if codec == 1 {
                    let mut analysis = unwrap!(encoder.analyze(black_box(&pcm[..block])));
                    while !analysis.advance(256) {}
                    analysis
                } else {
                    unwrap!(encoder.analyze_variant(black_box(&pcm[..block]), options))
                };
                let selected = DWT::cycle_count();
                let frame = unwrap!(encoder.encode_analyzed(analysis, black_box(output)));
                black_box(&output[..frame.bytes]);
                let ended = DWT::cycle_count();
                (
                    selected.wrapping_sub(began),
                    ended.wrapping_sub(selected),
                    frame.bytes,
                    Some(frame),
                )
            };
            totals.select += select as u64;
            totals.emit += emit as u64;
            totals.maximum = totals.maximum.max(select + emit);
            totals.bytes += bytes;
            totals.samples += block;
            totals.frames += 1;
            if let Some(frame) = frame {
                match frame.subframe {
                    Subframe::Constant => totals.constant += 1,
                    Subframe::Verbatim => totals.verbatim += 1,
                    Subframe::Fixed {
                        order, rice_bits, ..
                    } => {
                        totals.orders[order as usize] += 1;
                        if rice_bits == 4 {
                            totals.rice4 += 1;
                        } else {
                            totals.rice5 += 1;
                        }
                    }
                }
                unwrap!(encoder.commit(frame));
            }
            // Executor/RTT work is outside the measured codec regions.
            Timer::after_micros(100).await;
        }
    }
    info!(
        "CPU_ROW data={} depth={} block={} codec={} order={} method={} search={} samples={} frames={} select={} emit={} max={} bytes={} o0={} o1={} o2={} o3={} o4={} verbatim={} constant={} rice4={} rice5={}",
        data,
        depth,
        block,
        codec,
        order,
        method,
        search,
        totals.samples,
        totals.frames,
        totals.select,
        totals.emit,
        totals.maximum,
        totals.bytes,
        totals.orders[0],
        totals.orders[1],
        totals.orders[2],
        totals.orders[3],
        totals.orders[4],
        totals.verbatim,
        totals.constant,
        totals.rice4,
        totals.rice5
    );
    Timer::after_millis(10).await;
}

#[embassy_executor::main]
async fn main(_spawner: Spawner) -> ! {
    let (config, correction) = unwrap!(common::mcu_config_with_hse_error_ppm(-9));
    let _peripherals = embassy_stm32::init(config);
    let pll_n = correction.integer_n();
    let pll_fracn = correction.fracn();
    correction.apply();
    let _core = unwrap!(Stm32CoreDriver::init(CoreConfig {
        supply: CoreSupply::Smps
    }));
    let mut core = unwrap!(cortex_m::Peripherals::take());
    core.DCB.enable_trace();
    core.DWT.enable_cycle_counter();
    let began = Instant::now();
    let cycles = DWT::cycle_count();
    Timer::after_millis(100).await;
    let measured = DWT::cycle_count().wrapping_sub(cycles);
    let micros = began.elapsed().as_micros();
    // Scale from the full source recording's range, not the excerpt peaks.
    let width = include_str!("../../target/flac-cpu/signed_width.txt")
        .trim()
        .parse::<u8>()
        .unwrap();
    let production_order = if cfg!(feature = "cpu-benchmark-fixed-order1") {
        1u8
    } else {
        255u8
    };
    info!(
        "CPU_META nominal_hz=144000000 measured_cycles={} measured_us={} corpus_samples={} signed_width={} repeats={} pll_n={} pll_fracn={} supply=smps production_order={}",
        measured,
        micros,
        CORPUS.len() / 4,
        width,
        REPEATS,
        pll_n,
        pll_fracn,
        production_order
    );
    let pcm = PCM.take();
    let output = FRAME.take();
    for data in 0..=2 {
        for depth in [8u8, 16, 24, 32] {
            for block in [1024usize, 2048, 4096] {
                run(pcm, output, width, data, depth, block, 0, 255, 0, 0).await;
                run(
                    pcm,
                    output,
                    width,
                    data,
                    depth,
                    block,
                    1,
                    production_order,
                    0,
                    0,
                )
                .await;
                if data == 0 && !cfg!(feature = "cpu-benchmark-fixed-order1") {
                    let searches: &[u8] = if cfg!(feature = "cpu-benchmark-fused-mean") {
                        &[3]
                    } else {
                        &[0, 1, 2]
                    };
                    for &search in searches {
                        for order in [255u8, 0, 1, 2, 3, 4] {
                            for method in 0..=2 {
                                run(
                                    pcm, output, width, data, depth, block, 2, order, method,
                                    search,
                                )
                                .await;
                            }
                        }
                    }
                }
            }
        }
    }
    info!(
        "CPU_BENCH_DONE rows={}",
        if cfg!(feature = "cpu-benchmark-fixed-order1") {
            72usize
        } else if cfg!(feature = "cpu-benchmark-fused-mean") {
            288usize
        } else {
            720usize
        }
    );
    Timer::after_millis(100).await;
    // Let probe-rs close its USB session normally, rather than killing it.
    cortex_m_semihosting::debug::exit(cortex_m_semihosting::debug::EXIT_SUCCESS);
    loop {
        Timer::after_secs(60).await;
    }
}
